function catalog = build_arch2025_extended_wrappers( ...
        repoDirectory, generatedDirectory, officialRootDirectory, ...
        falBenchRootDirectory)
%BUILD_ARCH2025_EXTENDED_WRAPPERS Build SC, F16, and SB Falsify models.
%
% The SC wrapper embeds the official steam-condenser subsystem directly.
% The F16 wrapper samples the official nonlinear ODE runner through a
% static-initial-condition adapter.  The SB wrappers execute the selected
% FalBenchGen LSTM one recurrent step per simulated second.

    arguments
        repoDirectory (1, :) char
        generatedDirectory (1, :) char
        officialRootDirectory (1, :) char
        falBenchRootDirectory (1, :) char
    end

    assert(isfolder(generatedDirectory), ...
        'Generated wrapper directory was not found: %s', ...
        generatedDirectory);
    assert(isfolder(officialRootDirectory), ...
        'Official ARCH-COMP directory was not found: %s', ...
        officialRootDirectory);
    assert(isfolder(falBenchRootDirectory), ...
        'FalBenchGen directory was not found: %s', ...
        falBenchRootDirectory);

    addpath(repoDirectory, '-begin');
    addpath(generatedDirectory, '-begin');
    addpath(fullfile(repoDirectory, 'autotrans'), '-begin');
    addpath(genpath(fullfile(repoDirectory, 's-taliro')), '-end');
    rehash path;

    sourceMonitorModelFile = fullfile( ...
        repoDirectory, 'autotrans', 'autotrans_mod04.slx');

    catalog = struct();

    steamSourceFile = fullfile( ...
        officialRootDirectory, 'steam-condenser', ...
        'steamcondense_RNN_22.slx');

    catalog.SC_I1 = buildSteamWrapper_( ...
        steamSourceFile, sourceMonitorModelFile, generatedDirectory, ...
        'steamcondense_RNN_22_ARCH2025_I1', ...
        'rl_agent_arch2025_linear', 5.0);

    catalog.SC_I2 = buildSteamWrapper_( ...
        steamSourceFile, sourceMonitorModelFile, generatedDirectory, ...
        'steamcondense_RNN_22_ARCH2025_I2', ...
        'rl_agent_arch2025_pconst', 35 / 20);

    f16OfficialDirectory = fullfile( ...
        officialRootDirectory, 'f16-gcas');
    f16CompatibilityDirectory = fullfile( ...
        repoDirectory, 'arch2025_compat', 'f16');

    catalog.F16 = buildF16Wrapper_( ...
        sourceMonitorModelFile, generatedDirectory, ...
        'f16_gcas_ARCH2025', f16OfficialDirectory, ...
        f16CompatibilityDirectory);

    sbSpecs = {
        'S1',  's1',  1, [-50 50], ...
        fullfile('Model', 'Model_matlab_delta=2', ...
            's1a2_k1_1_4_9_10_0.01_LSTM', 's1a2_k1_1.mat')
        'S3',  's3',  1, [0 100], ...
        fullfile('Model', 'Model_matlab_delta=2', ...
            's3a2_k1_1_4_9_10_0.01_LSTM', 's3a2_k1_1.mat')
        'S5',  's5',  1, [-50 50], ...
        fullfile('Model', 'Model_matlab_delta=2', ...
            's5a2_k1_1_4_9_10_0.01_LSTM', 's5a2_k1_1.mat')
        'CC3', 'cc3', 2, repmat([-100 100], 2, 1), ...
        fullfile('Model', 'Model_matlab_cc35a', ...
            'cc3a2_k1_1_4_9_10_0.01_LSTM', 'cc3a2_k1_1.mat')
        'CC5', 'cc5', 2, repmat([-100 100], 2, 1), ...
        fullfile('Model', 'Model_matlab_cc35a', ...
            'cc5a2_k1_1_4_9_10_0.01_LSTM', 'cc5a2_k1_1.mat')
    };

    for row = 1:size(sbSpecs, 1)
        catalogField = ['SB_', sbSpecs{row, 1}];
        shortName = sbSpecs{row, 2};
        outputDimension = sbSpecs{row, 3};
        outputRange = sbSpecs{row, 4};
        networkFile = fullfile( ...
            falBenchRootDirectory, sbSpecs{row, 5});

        assert(isfile(networkFile), ...
            'Selected FalBenchGen network was not found: %s', networkFile);

        catalog.(catalogField) = buildSbWrapper_( ...
            sourceMonitorModelFile, generatedDirectory, ...
            ['falbench_', shortName, '_ARCH2025'], ...
            networkFile, outputDimension, outputRange);
    end

    bdclose('all');
end


function modelName = buildSteamWrapper_( ...
        sourceFile, monitorModelFile, generatedDirectory, ...
        modelName, agentClass, sampleTime)

    assert(isfile(sourceFile), ...
        'Official steam-condenser model was not found: %s', sourceFile);
    targetFile = fullfile(generatedDirectory, [modelName, '.slx']);

    if reusableModel_(targetFile, modelName, 'RL agent', {
            'System', agentClass
            'sample_time', num2str(sampleTime, 17)})
        return;
    end

    bdclose('all');
    if isfile(targetFile)
        delete(targetFile);
    end

    sourceHandle = load_system(sourceFile);
    sourceName = get_param(sourceHandle, 'Name');
    save_system(sourceName, targetFile);
    close_system(sourceName, 0);

    load_system(targetFile);
    load_system(monitorModelFile);
    monitorSourceName = modelNameFromFile_(monitorModelFile);

    subsystem = [modelName, '/Subsystem'];
    subsystemPorts = get_param(subsystem, 'PortHandles');
    pressureSource = subsystemPorts.Outport(4);
    physicalInput = subsystemPorts.Inport(1);

    originalInputLine = get_param(physicalInput, 'Line');
    if originalInputLine ~= -1
        delete_line(originalInputLine);
    end

    deleteIfPresent_([modelName, '/Fs']);
    for blockName = {'T', 'Fcw', 'Q', 'pressure'}
        deleteIfPresent_([modelName, '/', blockName{1}]);
    end

    addFalsifyShell_( ...
        modelName, monitorSourceName, agentClass, ...
        sampleTime, [3.99 4.01], 1, [0 200]);

    agentPorts = get_param([modelName, '/RL agent'], 'PortHandles');
    add_line(modelName, agentPorts.Outport(1), physicalInput, ...
        'autorouting', 'on');
    connectStateAndShell_(modelName, pressureSource);

    set_param(modelName, ...
        'LoadExternalInput', 'off', ...
        'SaveTime', 'on', ...
        'TimeSaveName', 'tout', ...
        'SaveOutput', 'on', ...
        'OutputSaveName', 'yout', ...
        'SaveFormat', 'Dataset');

    save_system(modelName);
    bdclose('all');
end


function modelName = buildF16Wrapper_( ...
        monitorModelFile, generatedDirectory, modelName, ...
        officialDirectory, compatibilityDirectory)

    targetFile = fullfile(generatedDirectory, [modelName, '.slx']);
    if reusableModel_(targetFile, modelName, 'Official F16 plant', {
            'System', 'arch2025_f16_plant'
            'official_directory', officialDirectory
            'compatibility_directory', compatibilityDirectory})
        return;
    end
    createEmptyModel_(modelName, targetFile, 0.01);
    load_system(monitorModelFile);
    monitorSourceName = modelNameFromFile_(monitorModelFile);

    inputRange = [
        pi / 4 - pi / 20, pi / 4 + pi / 30
        -0.8 * pi / 2, -0.8 * pi / 2 + pi / 20
        -pi / 4 - pi / 8, -pi / 4 + pi / 8
    ];

    addFalsifyShell_( ...
        modelName, monitorSourceName, 'rl_agent_arch2025_pconst', ...
        16.0, inputRange, 1, [-5000 5000]);

    add_block( ...
        [monitorSourceName, '/RL agent'], ...
        [modelName, '/Official F16 plant'], ...
        'Position', [160 90 300 140]);
    set_param([modelName, '/Official F16 plant'], ...
        'System', 'arch2025_f16_plant', ...
        'SimulateUsing', 'Interpreted execution', ...
        'sample_time', '0.01', ...
        'stop_time', '15', ...
        'official_directory', officialDirectory, ...
        'compatibility_directory', compatibilityDirectory);

    agentPorts = get_param([modelName, '/RL agent'], 'PortHandles');
    plantPorts = get_param( ...
        [modelName, '/Official F16 plant'], 'PortHandles');
    add_line(modelName, agentPorts.Outport(1), plantPorts.Inport(1), ...
        'autorouting', 'on');
    connectStateAndShell_(modelName, plantPorts.Outport(1));

    save_system(modelName);
    bdclose('all');
end


function modelName = buildSbWrapper_( ...
        monitorModelFile, generatedDirectory, modelName, ...
        networkFile, outputDimension, outputRange)

    targetFile = fullfile(generatedDirectory, [modelName, '.slx']);
    if reusableModel_(targetFile, modelName, 'FalBenchGen LSTM', {
            'System', 'arch2025_sb_network'
            'network_file', networkFile
            'output_dimension', num2str(outputDimension)})
        return;
    end
    createEmptyModel_(modelName, targetFile, 1.0);
    load_system(monitorModelFile);
    monitorSourceName = modelNameFromFile_(monitorModelFile);

    addFalsifyShell_( ...
        modelName, monitorSourceName, 'rl_agent_arch2025_pconst', ...
        6.0, [0 1], outputDimension, outputRange);

    add_block( ...
        [monitorSourceName, '/RL agent'], ...
        [modelName, '/FalBenchGen LSTM'], ...
        'Position', [160 90 300 140]);
    set_param([modelName, '/FalBenchGen LSTM'], ...
        'System', 'arch2025_sb_network', ...
        'SimulateUsing', 'Interpreted execution', ...
        'sample_time', '1', ...
        'sequence_length', '24', ...
        'output_dimension', num2str(outputDimension), ...
        'network_file', networkFile);

    agentPorts = get_param([modelName, '/RL agent'], 'PortHandles');
    networkPorts = get_param( ...
        [modelName, '/FalBenchGen LSTM'], 'PortHandles');
    add_line(modelName, agentPorts.Outport(1), networkPorts.Inport(1), ...
        'autorouting', 'on');
    connectStateAndShell_(modelName, networkPorts.Outport(1));

    save_system(modelName);
    bdclose('all');
end


function addFalsifyShell_( ...
        modelName, monitorSourceName, agentClass, sampleTime, ...
        inputRange, observationDimension, outputRange)

    add_block( ...
        [monitorSourceName, '/RL agent'], ...
        [modelName, '/RL agent'], ...
        'Position', [20 80 120 140]);
    set_param([modelName, '/RL agent'], ...
        'System', agentClass, ...
        'sample_time', num2str(sampleTime, 17), ...
        'input_range', mat2str(inputRange, 17), ...
        'observation_dimension', num2str(observationDimension));

    add_block( ...
        [monitorSourceName, '/TaLiRo_Monitor'], ...
        [modelName, '/TaLiRo_Monitor'], ...
        'Position', [520 175 650 215]);

    lower = outputRange(:, 1);
    upper = outputRange(:, 2);
    middle = (lower + upper) / 2;
    halfSpan = (upper - lower) / 2;
    assert(all(halfSpan > 0), 'Output ranges must have positive width.');

    add_block( ...
        'simulink/Math Operations/Bias', ...
        [modelName, '/State center'], ...
        'Bias', mat2str(-middle, 17), ...
        'Position', [330 90 390 130]);
    add_block( ...
        'simulink/Math Operations/Gain', ...
        [modelName, '/State normalize'], ...
        'Gain', mat2str(1 ./ halfSpan, 17), ...
        'Multiplication', 'Element-wise(K.*u)', ...
        'Position', [420 90 480 130]);

    add_block( ...
        'simulink/Sinks/Out1', ...
        [modelName, '/RewardOut'], ...
        'Port', '1', ...
        'Position', [700 180 730 200]);
    add_block( ...
        'simulink/Sinks/Out1', ...
        [modelName, '/StateOut'], ...
        'Port', '2', ...
        'Position', [700 100 730 120]);
    add_block( ...
        'simulink/Sinks/Out1', ...
        [modelName, '/ActionOut'], ...
        'Port', '3', ...
        'Position', [700 40 730 60]);

    agentPorts = get_param([modelName, '/RL agent'], 'PortHandles');
    monitorPorts = get_param( ...
        [modelName, '/TaLiRo_Monitor'], 'PortHandles');
    actionOutPorts = get_param([modelName, '/ActionOut'], 'PortHandles');
    rewardOutPorts = get_param([modelName, '/RewardOut'], 'PortHandles');

    add_line(modelName, agentPorts.Outport(1), actionOutPorts.Inport(1), ...
        'autorouting', 'on');
    add_line(modelName, monitorPorts.Outport(1), agentPorts.Inport(2), ...
        'autorouting', 'on');
    add_line(modelName, monitorPorts.Outport(1), rewardOutPorts.Inport(1), ...
        'autorouting', 'on');

    set_param(modelName, ...
        'SaveTime', 'on', ...
        'TimeSaveName', 'tout', ...
        'SaveOutput', 'on', ...
        'OutputSaveName', 'yout', ...
        'SaveFormat', 'Dataset');
end


function connectStateAndShell_(modelName, rawStateSource)

    centerPorts = get_param([modelName, '/State center'], 'PortHandles');
    normalizePorts = get_param( ...
        [modelName, '/State normalize'], 'PortHandles');
    agentPorts = get_param([modelName, '/RL agent'], 'PortHandles');
    monitorPorts = get_param( ...
        [modelName, '/TaLiRo_Monitor'], 'PortHandles');
    stateOutPorts = get_param([modelName, '/StateOut'], 'PortHandles');

    add_line(modelName, rawStateSource, centerPorts.Inport(1), ...
        'autorouting', 'on');
    add_line(modelName, centerPorts.Outport(1), normalizePorts.Inport(1), ...
        'autorouting', 'on');
    add_line(modelName, normalizePorts.Outport(1), agentPorts.Inport(1), ...
        'autorouting', 'on');
    add_line(modelName, normalizePorts.Outport(1), monitorPorts.Inport(1), ...
        'autorouting', 'on');
    add_line(modelName, normalizePorts.Outport(1), stateOutPorts.Inport(1), ...
        'autorouting', 'on');
end


function createEmptyModel_(modelName, targetFile, fixedStep)

    bdclose('all');
    if isfile(targetFile)
        delete(targetFile);
    end
    new_system(modelName);
    open_system(modelName);
    set_param(modelName, ...
        'Solver', 'FixedStepDiscrete', ...
        'FixedStep', num2str(fixedStep, 17), ...
        'LoadExternalInput', 'off', ...
        'SaveFormat', 'Dataset');
    save_system(modelName, targetFile);
end


function deleteIfPresent_(block)
    if getSimulinkBlockHandle(block) ~= -1
        delete_block(block);
    end
end


function reusable = reusableModel_( ...
        targetFile, modelName, blockName, expectedParameters)
% Reuse a generated wrapper when its source-dependent configuration matches.

    reusable = false;
    if strcmp(getenv('FALSIFY_ARCH2025_REBUILD_WRAPPERS'), '1') || ...
            ~isfile(targetFile)
        return;
    end

    try
        bdclose(modelName);
        load_system(targetFile);
        cleanup = onCleanup(@() close_system(modelName, 0));
        block = [modelName, '/', blockName];
        if getSimulinkBlockHandle(block) == -1
            return;
        end

        for row = 1:size(expectedParameters, 1)
            actual = string(get_param(block, expectedParameters{row, 1}));
            expected = string(expectedParameters{row, 2});
            if actual ~= expected
                return;
            end
        end
        reusable = true;
    catch
        reusable = false;
    end
end


function name = modelNameFromFile_(modelFile)
    [~, name] = fileparts(modelFile);
end
