function plot_arch2025_rl_experiment(summaryFile, outputFile)
%PLOT_ARCH2025_RL_EXPERIMENT Plot official violation rates and Wilson CIs.

arguments
    summaryFile (1, 1) string
    outputFile (1, 1) string
end

results = readtable(summaryFile, 'TextType', 'string');
required = [ ...
    "Algorithm", ...
    "PipelineValidRuns", ...
    "OfficialViolations", ...
    "OfficialViolationRate", ...
    "OfficialViolationRateCI95Low", ...
    "OfficialViolationRateCI95High" ...
];
assert(all(ismember(required, string(results.Properties.VariableNames))), ...
    'The summary CSV does not contain the required columns.');

rates = results.OfficialViolationRate;
lowerErrors = rates - results.OfficialViolationRateCI95Low;
upperErrors = results.OfficialViolationRateCI95High - rates;
positions = 1:height(results);

figureHandle = figure( ...
    'Visible', 'off', ...
    'Color', 'white', ...
    'Position', [100, 100, 900, 560] ...
);
cleanup = onCleanup(@() close(figureHandle));

bar(positions, rates, 0.68, 'FaceColor', [0.20, 0.48, 0.72]);
hold on;
errorbar( ...
    positions, rates, lowerErrors, upperErrors, ...
    'k.', 'LineWidth', 1.6, 'CapSize', 12 ...
);
hold off;

axesHandle = gca;
axesHandle.XTick = positions;
axesHandle.XTickLabel = cellstr(results.Algorithm);
axesHandle.FontSize = 12;
axesHandle.Color = 'white';
axesHandle.XColor = 'black';
axesHandle.YColor = 'black';
axesHandle.YGrid = 'on';
axesHandle.GridAlpha = 0.25;
ylim([0, 1.10]);
ylabel('Official violation discovery rate', 'Color', 'black');
title( ...
    'CC3 Instance 2: 30 episodes, 20 matched seeds', ...
    'Color', 'black' ...
);

for index = positions
    label = sprintf( ...
        '%d/%d', ...
        results.OfficialViolations(index), ...
        results.PipelineValidRuns(index) ...
    );
    text( ...
        index, min(1.075, results.OfficialViolationRateCI95High(index) + 0.04), ...
        label, ...
        'HorizontalAlignment', 'center', ...
        'FontWeight', 'bold', ...
        'Color', 'black' ...
    );
end

outputDirectory = fileparts(outputFile);
if strlength(outputDirectory) > 0 && ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end
exportgraphics(figureHandle, outputFile, 'Resolution', 200);
end
