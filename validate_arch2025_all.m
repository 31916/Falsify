function rawState = denormalizeState_( ...
        normalizedState, ...
        outputRange)

    lower = outputRange(:, 1)';
    upper = outputRange(:, 2)';

    middle = (lower + upper) / 2;
    halfRange = (upper - lower) / 2;

    rawState = ...
        normalizedState .* ...
        halfRange + ...
        middle;
end


function [maximumError, ...
        pass] = trajectoryDiagnostic_( ...
        falsifyTime, ...
        falsifyState, ...
        officialTime, ...
        officialState, ...
        stopTime, ...
        settings)

    commonTime = ...
        (0:round(stopTime / settings.TraceStep))' ...
        * settings.TraceStep;

    try

        falsifyOnGrid = ...
            resampleContinuousSignal_( ...
                falsifyTime, ...
                falsifyState, ...
                commonTime ...
            );

        officialOnGrid = ...
            resampleContinuousSignal_( ...
                officialTime, ...
                officialState, ...
                commonTime ...
            );

        maximumError = ...
            max(abs( ...
                falsifyOnGrid - ...
                officialOnGrid ...
            ), [], 'all');

        pass = ...
            maximumError <= ...
            settings.TrajectoryTolerance;

    catch

        maximumError = NaN;
        pass = false;
    end
end


function result = sameClassification_( ...
        firstRobustness, ...
        secondRobustness, ...
        tolerance)

    firstClass = robustnessClass_( ...
        firstRobustness, ...
        tolerance ...
    );

    secondClass = robustnessClass_( ...
        secondRobustness, ...
        tolerance ...
    );

    result = ...
        firstClass == secondClass;
end


function value = robustnessClass_(robustness, tolerance)

    if robustness < -tolerance
        value = -1;
    elseif robustness > tolerance
        value = 1;
    else
        value = 0;
    end
end


function value = robustnessClassText_(robustness, tolerance)

    switch robustnessClass_(robustness, tolerance)
        case -1
            value = "VIOLATED";
        case 1
            value = "SATISFIED";
        otherwise
            value = "BOUNDARY";
    end
end


function [time, ...
        data, ...
        elementName] = readDatasetElement_( ...
        dataset, ...
        elementIndex)

    element = ...
        dataset.getElement(elementIndex);

    values = ...
        element.Values;

    time = ...
        double(values.Time(:));

    data = ...
        double(squeeze(values.Data));

    if isvector(data)

        if numel(data) == numel(time)
            data = data(:);
        else
            data = reshape(data, 1, []);
        end
    end

    if size(data, 1) ~= numel(time) && ...
            size(data, 2) == numel(time)

        data = data.';
    end

    assert(size(data, 1) == numel(time), ...
        [ ...
            'Dataset element %d has incompatible dimensions.\n' ...
            'Time samples: %d\n' ...
            'Data: %d x %d' ...
        ], ...
        elementIndex, ...
        numel(time), ...
        size(data, 1), ...
        size(data, 2));

    try
        elementName = string(element.Name);
    catch
        elementName = ...
            "Element " + string(elementIndex);
    end

    if strlength(elementName) == 0
        elementName = ...
            "Element " + string(elementIndex);
    end
end


function [uniqueTime, ...
        uniqueData] = uniqueTimeSeriesLast_( ...
        originalTime, ...
        originalData)

    originalTime = double(originalTime(:));
    originalData = double(originalData);

    [sortedTime, ...
        sortIndex ...
    ] = sort(originalTime);

    sortedData = ...
        originalData(sortIndex, :);

    [uniqueTime, ...
        uniqueIndex ...
    ] = unique( ...
        sortedTime, ...
        'last' ...
    );

    uniqueData = ...
        sortedData(uniqueIndex, :);
end


function output = resampleContinuousSignal_( ...
        originalTime, ...
        originalData, ...
        targetTime)

    [uniqueTime, ...
        uniqueData ...
    ] = uniqueTimeSeriesLast_( ...
        originalTime, ...
        originalData ...
    );

    targetTime = double(targetTime(:));

    endpointTolerance = 1.0e-8;

    targetTime( ...
        abs(targetTime - uniqueTime(1)) <= ...
        endpointTolerance ...
    ) = uniqueTime(1);

    targetTime( ...
        abs(targetTime - uniqueTime(end)) <= ...
        endpointTolerance ...
    ) = uniqueTime(end);

    assert(min(targetTime) >= ...
        uniqueTime(1) - endpointTolerance);

    assert(max(targetTime) <= ...
        uniqueTime(end) + endpointTolerance);

    output = interp1( ...
        uniqueTime, ...
        uniqueData, ...
        targetTime, ...
        'linear' ...
    );

    assert(~any(isnan(output), 'all'));
end


