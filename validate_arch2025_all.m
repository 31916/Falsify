function createPconstAgent_( ...
        sourceAgentFile, ...
        targetAgentFile, ...
        sourceClass, ...
        targetClass)

    assert(isfile(sourceAgentFile), ...
        'Source agent was not found:\n%s', ...
        sourceAgentFile);

    lines = readlines(sourceAgentFile);

    classIndex = find( ...
        contains( ...
            lines, ...
            "classdef " + sourceClass ...
        ), ...
        1 ...
    );

    assert(~isempty(classIndex), ...
        'Class definition was not found in:\n%s', ...
        sourceAgentFile);

    lines(classIndex) = replace( ...
        lines(classIndex), ...
        "classdef " + sourceClass, ...
        "classdef " + targetClass ...
    );

    outputStart = find( ...
        contains( ...
            lines, ...
            'function action = outputImpl' ...
        ), ...
        1 ...
    );

    assert(~isempty(outputStart), ...
        'outputImpl was not found in:\n%s', ...
        sourceAgentFile);

    outputEnd = [];

    for lineIndex = outputStart + 1:numel(lines)

        currentLine = char(lines(lineIndex));

        if ~isempty(regexp( ...
                currentLine, ...
                '^\s{8}end\s*$', ...
                'once' ...
            ))

            outputEnd = lineIndex;
            break;
        end
    end

    assert(~isempty(outputEnd), ...
        'The end of outputImpl was not found in:\n%s', ...
        sourceAgentFile);

    replacement = [
        "        function sampleTimeSpecification = getSampleTimeImpl(obj)"
        ""
        "            sampleTimeSpecification = createSampleTime( ..."
        "                obj, ..."
        "                'Type', 'Discrete', ..."
        "                'SampleTime', obj.sample_time, ..."
        "                'OffsetTime', 0 ..."
        "            );"
        "        end"
        ""
        ""
        "        function action = outputImpl(obj, ~, ~)"
        "            action = obj.action';"
        "        end"
    ];

    lines = [
        lines(1:outputStart - 1)
        replacement
        lines(outputEnd + 1:end)
    ];

    lastTimeMatches = false(size(lines));

    for lineIndex = 1:numel(lines)

        updatedLine = regexprep( ...
            char(lines(lineIndex)), ...
            'obj\.last_t\s*=\s*0(?:\.0)?\s*;', ...
            'obj.last_t = -obj.sample_time;' ...
        );

        if ~strcmp(updatedLine, char(lines(lineIndex)))
            lastTimeMatches(lineIndex) = true;
            lines(lineIndex) = string(updatedLine);
        end
    end

    if ~any(lastTimeMatches)

        warning( ...
            'ARCH2025:LastTimeNotRewritten', ...
            [ ...
                'No obj.last_t = 0 initialization was found in:\n%s\n' ...
                'The generated class was still written, but its first ' ...
                'action update must be checked by input validation.' ...
            ], ...
            sourceAgentFile ...
        );
    end

    writelines(lines, targetAgentFile);
    rehash path;

    resolved = which(targetClass);

    assert(~isempty(resolved), ...
        'MATLAB cannot resolve generated class %s.', ...
        targetClass);

    assert(strcmp(resolved, targetAgentFile), ...
        [ ...
            'Wrong generated agent was resolved.\n' ...
            'Expected: %s\n' ...
            'Actual:   %s' ...
        ], ...
        targetAgentFile, ...
        resolved);
end


