            py.sys.path, ...
            char(repoDirectory) ...
        )) == 0

        insert( ...
            py.sys.path, ...
            int32(0), ...
            char(repoDirectory) ...
        );
    end

    py.importlib.invalidate_caches();

    driverModule = ...
        py.importlib.import_module('driver');

    py.importlib.reload(driverModule);
end


