% =========================================================
% Input validation and official 0.01-second trace
% =========================================================

function [overallPass, ...
        rangePass, ...
        structurePass, ...
        message, ...
        officialTime, ...
        officialData] = validateAndCreateOfficialInput_( ...
        currentCase, ...
        actionTime, ...
        actionData, ...
        inputRange, ...
        settings)

    stopTime = currentCase.StopTime;

    validationTime = actionTime;
    validationData = actionData;

    terminalActionTime = NaN;
    f16StaticPass = true;

    if currentCase.Instance == 2 || currentCase.Model == "SB"

        switch currentCase.Model

            case "CC"
                terminalActionTime = stopTime;

            case "AFC"
                % The ten selected values cover [0,50]. The value emitted
                % at 50 s would start an invalid eleventh segment.
                terminalActionTime = 50;

            case "SC"
                terminalActionTime = stopTime;

            case "SB"
                terminalActionTime = stopTime;
        end
    end

    if ~isnan(terminalActionTime)

        [validationTime, ...
            validationData ...
        ] = canonicalizeInstance2TerminalHold_( ...
            validationTime, ...
            validationData, ...
            terminalActionTime, ...
            stopTime, ...
            settings.ChangeTimeTolerance, ...
            currentCase.Model ...
        );
    end

    if currentCase.Model == "NN" && ...
            currentCase.Instance == 2

        [validationTime, ...
            validationData ...
        ] = canonicalizeNnInstance2Input_( ...
            validationTime, ...
            validationData, ...
            stopTime, ...
            settings.TraceStep ...
        );
    end

    if currentCase.Model == "F16"

        [staticTime, staticData] = ...
            uniqueTimeSeriesLast_(validationTime, validationData);

        assert(~isempty(staticTime), ...
            'F16 did not log its static initial-condition action.');

        f16StaticPass = all( ...
            max(staticData, [], 1) - min(staticData, [], 1) <= ...
            settings.InputTolerance ...
        );

        validationTime = [0; stopTime];
        validationData = repmat(staticData(1, :), 2, 1);
    end

    officialTime = ...
        (0:round(stopTime / settings.TraceStep))' ...
        * settings.TraceStep;

    if currentCase.Interpolation == "pconst"
        interpolationMethod = 'previous';
    else
        interpolationMethod = 'linear';
    end

    officialData = interp1( ...
        validationTime, ...
        validationData, ...
        officialTime, ...
        interpolationMethod, ...
        'extrap' ...
    );

    lowerBounds = inputRange(:, 1)';
    upperBounds = inputRange(:, 2)';

    rangePass = ...
        all( ...
            min(officialData, [], 1) >= ...
            lowerBounds - settings.InputTolerance ...
        ) && ...
        all( ...
            max(officialData, [], 1) <= ...
            upperBounds + settings.InputTolerance ...
        );

    structurePass = true;
    details = strings(0, 1);

    requiresFixedSegments = ...
        currentCase.Instance == 2 || currentCase.Model == "SB";

    if requiresFixedSegments

        boundaries = instance2Boundaries_(currentCase);

        for segmentIndex = 1:numel(boundaries) - 1

            segmentStart = boundaries(segmentIndex);
            segmentEnd = boundaries(segmentIndex + 1);

            rows = ...
                officialTime >= ...
                    segmentStart + settings.TraceStep & ...
                officialTime <= ...
                    segmentEnd - settings.TraceStep;

            if ~any(rows)
                structurePass = false;
                details(end + 1) = ...
                    "segment " + string(segmentIndex) + ...
                    " has no interior samples"; %#ok<AGROW>
                continue;
            end

            segmentSpan = ...
                max(officialData(rows, :), [], 1) - ...
                min(officialData(rows, :), [], 1);

            if any(segmentSpan > settings.InputTolerance)

                structurePass = false;

                details(end + 1) = ...
                    "segment " + string(segmentIndex) + ...
                    " is not constant"; %#ok<AGROW>
            end
        end

        observedChangeTimes = ...
            detectChangeTimes_( ...
                validationTime, ...
                validationData, ...
                settings.InputTolerance ...
            );

        allowedChangeTimes = ...
            boundaries(2:end - 1);

        for changeIndex = 1:numel(observedChangeTimes)

            if isempty(allowedChangeTimes) || ...
                    min(abs( ...
                        allowedChangeTimes - ...
                        observedChangeTimes(changeIndex) ...
                    )) > settings.ChangeTimeTolerance

                structurePass = false;

                details(end + 1) = ...
                    "unexpected change time " + ...
                    string(observedChangeTimes(changeIndex)); %#ok<AGROW>
            end
        end
    end

    if currentCase.Model == "F16"
        structurePass = structurePass && f16StaticPass;

        if ~f16StaticPass
            details(end + 1) = ...
                "F16 initial conditions changed during the episode"; %#ok<AGROW>
        end
    end

    if currentCase.Model == "AFC"

        engineSpeedSpan = ...
            max(officialData(:, 2)) - ...
            min(officialData(:, 2));

        engineSpeedConstant = ...
            engineSpeedSpan <= settings.InputTolerance;

        engineSpeedInRange = ...
            min(officialData(:, 2)) >= ...
                900 - settings.InputTolerance && ...
            max(officialData(:, 2)) < ...
                1100 + settings.InputTolerance;

        structurePass = ...
            structurePass && ...
            engineSpeedConstant && ...
            engineSpeedInRange;

        if ~engineSpeedConstant
            details(end + 1) = ...
                "engine speed is not constant"; %#ok<AGROW>
        end

        if ~engineSpeedInRange
            details(end + 1) = ...
                "engine speed is outside [900,1100)"; %#ok<AGROW>
        end
    end

    overallPass = ...
        rangePass && ...
        structurePass;

    if isempty(details)

        message = "all input checks passed";

    else

        message = strjoin(details, "; ");
    end
end


function [canonicalTime, ...
        canonicalData] = canonicalizeInstance2TerminalHold_( ...
        time, ...
        data, ...
        terminalActionTime, ...
        stopTime, ...
        endpointTolerance, ...
        modelName)

    [uniqueTime, ...
        uniqueData ...
    ] = uniqueTimeSeriesLast_(time, data);

    preterminalRows = ...
        uniqueTime < terminalActionTime - endpointTolerance;

    assert(any(preterminalRows), ...
        '%s Instance 2 input has no samples before the terminal action.', ...
        modelName);

    assert(stopTime >= terminalActionTime, ...
        '%s stop time precedes its terminal action time.', ...
        modelName);

    canonicalTime = uniqueTime(preterminalRows);
    canonicalData = uniqueData(preterminalRows, :);

    % An action emitted at the terminal boundary is never applied over a
    % new input segment. Hold the last value that was active before that
    % boundary through the official replay horizon instead.
    canonicalTime(end + 1, 1) = terminalActionTime;
    canonicalData(end + 1, :) = canonicalData(end, :);

    if stopTime > terminalActionTime + endpointTolerance
        canonicalTime(end + 1, 1) = stopTime;
        canonicalData(end + 1, :) = canonicalData(end, :);
    end
end


function [canonicalTime, ...
        canonicalData] = canonicalizeNnInstance2Input_( ...
        time, ...
        data, ...
        stopTime, ...
        traceStep)

    [uniqueTime, ...
        uniqueData ...
    ] = uniqueTimeSeriesLast_(time, data);

    boundaries = [
        0
        stopTime / 3
        2 * stopTime / 3
        stopTime
    ];

    % The discrete System object reports repeating-third events with
    % finite decimal times such as 13.3333 and 26.6666. Sample safely
    % inside each observed segment, then rebuild the official input at
    % the exact mathematical boundaries. This also discards the unused
    % action emitted immediately before the 40 s stop event.
    interiorTimes = ...
        boundaries(1:end - 1) + traceStep;

    assert(uniqueTime(1) <= interiorTimes(1) && ...
        uniqueTime(end) >= interiorTimes(end), ...
        'NN Instance 2 action log does not cover all three segments.');

    segmentData = interp1( ...
        uniqueTime, ...
        uniqueData, ...
        interiorTimes, ...
        'previous', ...
        'extrap' ...
    );

    canonicalTime = boundaries;
    canonicalData = [
        segmentData
        segmentData(end, :)
    ];
end


function boundaries = instance2Boundaries_(currentCase)

    switch currentCase.Model

        case "AT"
            boundaries = [0 5 10 15 20 25 30 33];

        case "AFC"
            % Ten input segments over [0,50].
            % The last selected value is held for the final simulation
            % second [50,51].
            boundaries = 0:5:50;

        case "CC"
            boundaries = 0:5:100;

        case "NN"
            boundaries = [
                0
                40 / 3
                80 / 3
                40
            ]';

        case "SC"
            boundaries = linspace(0, 35, 21);

        case "SB"
            boundaries = [0 6 12 18 24];

        otherwise
            error('Unknown model: %s', currentCase.Model);
    end
end


function changeTimes = detectChangeTimes_( ...
        time, ...
        data, ...
        tolerance)

    [uniqueTime, ...
        uniqueData ...
    ] = uniqueTimeSeriesLast_(time, data);

    difference = ...
        abs(diff(uniqueData, 1, 1));

    rows = ...
        find(any(difference > tolerance, 2));

    changeTimes = ...
        uniqueTime(rows + 1);
end


% =========================================================
% Official model replay
% =========================================================

function [officialTime, ...
        officialOutput] = runOfficialModel_( ...
        currentCase, ...
        inputTime, ...
        inputData, ...
        settings)

    officialDirectory = ...
        char(currentCase.OfficialDirectory);

    runFunction = ...
        char(currentCase.OfficialRunFunction);

    assert(isfolder(officialDirectory), ...
        'Official model directory was not found:\n%s', ...
        officialDirectory);

    oldDirectory = pwd;
    directoryCleanup = onCleanup(@() cd(oldDirectory));

    removeFalsifyModelPaths_(settings.RepoDirectory);

    cd(officialDirectory);
    addpath(officialDirectory, '-begin');
    rehash path;

    eval(['clear ', runFunction]);

    switch currentCase.Model

        case "AT"
            if exist('init_transmission', 'file') == 2
                init_transmission;
            end

        case "AFC"
            if exist('init_powertrain', 'file') == 2
                init_powertrain;
            end

        case "NN"
            % The compatibility replay below initializes u_ts in the
            % base workspace and supplies a column-oriented time vector.

        case "CC"
            % Nothing to initialize.

        case "F16"
            aeroBenchDirectory = fullfile( ...
                officialDirectory, 'AeroBenchVV-develop');
            compatibilityDirectory = char(currentCase.OfficialAsset);
            assert(isfolder(aeroBenchDirectory), ...
                'AeroBenchVV-develop was not found: %s', ...
                aeroBenchDirectory);
            assert(isfolder(compatibilityDirectory), ...
                'F16 compatibility directory was not found: %s', ...
                compatibilityDirectory);
            addpath(genpath(aeroBenchDirectory), '-begin');
            addpath(compatibilityDirectory, '-begin');
            rehash path;

        case {"SC", "SB"}
            % No initialization script is required.
    end

    officialInput = [
        inputTime, ...
        inputData
    ];

    if currentCase.Model == "AT"

        % The ARCH-COMP 2025 transmission runner keeps a legacy,
        % unused first argument before the input signal and horizon.
        [officialTime, ...
            officialOutput ...
        ] = feval( ...
            runFunction, ...
            [], ...
            officialInput, ...
            currentCase.StopTime ...
        );

    elseif currentCase.Model == "NN"

        % ARCH-COMP's run_neural helper constructs a row time vector and
        % concatenates it with column input data.  MATLAB R2026a rejects
        % that shape mismatch.  Reproduce the helper's intended replay
        % without modifying the official checkout.
        neuralTime = (0:0.01:currentCase.StopTime)';
        neuralData = interp1( ...
            inputTime, inputData, neuralTime, 'previous');
        neuralInput = [neuralTime, neuralData];

        assignin('base', 'u_ts', 0.001);
        assignin('base', 'u', neuralInput);
        assignin('base', 'T', currentCase.StopTime);

        load_system(fullfile( ...
            officialDirectory, 'narmamaglev_v1.slx'));
        simulationResult = sim( ...
            'narmamaglev_v1', ...
            'StopTime', num2str(currentCase.StopTime, 17), ...
            'LoadExternalInput', 'on', ...
            'ExternalInput', 'u', ...
            'SaveTime', 'on', ...
            'TimeSaveName', 'tout', ...
            'SaveOutput', 'on', ...
            'OutputSaveName', 'yout', ...
            'SaveFormat', 'Array');

        officialTime = simulationResult.tout;
        officialOutput = simulationResult.yout;

    elseif currentCase.Model == "SC"

        % The official helper passes the symbolic string "T" as StopTime,
        % which MATLAB R2026a rejects inside this function call.  Execute
        % the same official model and input with an explicit numeric string.
        assignin('base', 'u', officialInput);
        assignin('base', 'T', currentCase.StopTime);
        load_system(fullfile( ...
            officialDirectory, 'steamcondense_RNN_22.slx'));
        simulationResult = sim( ...
            'steamcondense_RNN_22', ...
            'StopTime', num2str(currentCase.StopTime, 17), ...
            'LoadExternalInput', 'on', ...
            'ExternalInput', 'u', ...
            'SaveTime', 'on', ...
            'TimeSaveName', 'tout', ...
            'SaveOutput', 'on', ...
            'OutputSaveName', 'yout', ...
            'SaveFormat', 'Array');
        officialTime = simulationResult.tout;
        officialOutput = simulationResult.yout;

    elseif currentCase.Model == "F16"

        staticInitialConditions = inputData(1, :);
        assert(numel(staticInitialConditions) == 3, ...
            'F16 official replay requires roll, pitch, and yaw.');
        warningState = warning;
        warningCleanup = onCleanup(@() warning(warningState)); %#ok<NASGU>
        warning('off', 'all');
        [officialTime, officialOutput] = ...
            run_arch2025_f16_compat( ...
            officialDirectory, ...
            4040, ...
            540, ...
            staticInitialConditions(1), ...
            staticInitialConditions(2), ...
            staticInitialConditions(3), ...
            currentCase.StopTime ...
        );

    elseif currentCase.Model == "SB"

        networkFile = char(currentCase.OfficialAsset);
        assert(isfile(networkFile), ...
            'FalBenchGen network was not found: %s', networkFile);
        loadedNetwork = load(networkFile, 'net');
        sequenceTime = (0:23)';
        sequenceInput = interp1( ...
            inputTime, inputData, sequenceTime, 'previous', 'extrap');
        prediction = predict( ...
            loadedNetwork.net, sequenceInput', 'MiniBatchSize', 1);
        officialTime = (0:24)';
        officialOutput = double(prediction');
        officialOutput(end + 1, :) = officialOutput(end, :);

    else

        [officialTime, ...
            officialOutput ...
        ] = feval( ...
            runFunction, ...
            officialInput, ...
            currentCase.StopTime ...
        );
    end

    officialTime = double(officialTime(:));
    officialOutput = double(officialOutput);

    if size(officialOutput, 1) ~= ...
            numel(officialTime) && ...
            size(officialOutput, 2) == ...
            numel(officialTime)

        officialOutput = officialOutput.';
    end

    assert(size(officialOutput, 1) == ...
        numel(officialTime), ...
        [ ...
            'Official output/time dimensions are incompatible.\n' ...
            'Time: %d\n' ...
            'Output: %d x %d' ...
        ], ...
        numel(officialTime), ...
        size(officialOutput, 1), ...
        size(officialOutput, 2));

    % Some Array-format configurations include time as column 1.
    if size(officialOutput, 2) >= 2

        firstColumn = ...
            officialOutput(:, 1);

        if max(abs( ...
                firstColumn - ...
                officialTime ...
            )) <= 1.0e-9

            officialOutput = ...
                officialOutput(:, 2:end);
        end
    end
end


function canonicalState = canonicalOfficialState_( ...
        currentCase, ...
        officialTime, ...
        officialOutput, ...
        inputTime, ...
        inputData)

    inputOnOfficialTime = ...
        interp1( ...
            inputTime, ...
            inputData, ...
            officialTime, ...
            'previous', ...
            'extrap' ...
        );

    switch currentCase.Model

        case "SB"

            canonicalState = officialOutput;

        case "AT"

            assert(size(officialOutput, 2) >= 3, ...
                'Official AT output must contain at least three signals.');

            candidate = officialOutput(:, 1:3);

            gearScore = inf(1, 3);

            for columnIndex = 1:3

                column = candidate(:, columnIndex);

                gearScore(columnIndex) = ...
                    mean(abs(column - round(column))) + ...
                    100 * mean( ...
                        column < 0.5 | ...
                        column > 6 ...
                    );
            end

            [~, gearIndex] = min(gearScore);

            remaining = setdiff(1:3, gearIndex);

            maxima = max(abs(candidate(:, remaining)), [], 1);

            [~, rpmRelativeIndex] = max(maxima);

            rpmIndex = remaining(rpmRelativeIndex);
            speedIndex = remaining( ...
                remaining ~= rpmIndex ...
            );

            canonicalState = [
                candidate(:, rpmIndex), ...
                candidate(:, speedIndex), ...
                candidate(:, gearIndex)
            ];

        case "AFC"

            throttle = inputOnOfficialTime(:, 1);
            engineSpeed = inputOnOfficialTime(:, 2);
            mode = double(throttle >= 61.2);

            if size(officialOutput, 2) >= 4

                canonicalState = ...
                    officialOutput(:, 1:4);

                % Force the externally defined input semantics.
                canonicalState(:, 2) = mode;
                canonicalState(:, 3) = throttle;
                canonicalState(:, 4) = engineSpeed;

            else

                mu = officialOutput(:, 1);

                canonicalState = [
                    mu, ...
                    mode, ...
                    throttle, ...
                    engineSpeed
                ];
            end

        case "CC"

            assert(size(officialOutput, 2) >= 5, ...
                'Official CC output must contain five positions.');

            positions = officialOutput(:, 1:5);

            canonicalState = ...
                diff(positions, 1, 2);

        case "NN"

            ref = inputOnOfficialTime(:, 1);

            % narmamaglev_v1 exposes root Outport 1 as Pos and root
            % Outport 2 as NNPos. Neither column is Ref; Ref is the
            % external benchmark input reconstructed above.
            assert(size(officialOutput, 2) >= 1, ...
                'Official NN output must contain Pos on root Outport 1.');
            pos = officialOutput(:, 1);

            canonicalState = [
                ref, ...
                pos
            ];

        case "F16"

            assert(size(officialOutput, 2) >= 1, ...
                'Official F16 output must contain altitude.');
            canonicalState = officialOutput(:, 1);

        case "SC"

            assert(size(officialOutput, 2) >= 4, ...
                'Official SC output must contain T, Fcw, Q, and pressure.');
            canonicalState = officialOutput(:, 4);

        otherwise

            error('Unknown model: %s', currentCase.Model);
    end
end


