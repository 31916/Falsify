function targetModelName = ensureActionWrapper_( ...
        sourceModelFile, ...
        generatedDirectory, ...
        targetModelName, ...
        agentClass)

    assert(isfile(sourceModelFile), ...
        'Source model was not found:\n%s', ...
        sourceModelFile);

    [~, ~, sourceExtension] = ...
        fileparts(sourceModelFile);

    targetModelFile = ...
        fullfile( ...
            generatedDirectory, ...
            [targetModelName, sourceExtension] ...
        );

    rebuild = true;

    forceRebuild = strcmp( ...
        getenv('FALSIFY_ARCH2025_REBUILD_WRAPPERS'), ...
        '1' ...
    );

    if isfile(targetModelFile) && ~forceRebuild

        try
            bdclose('all');

            targetHandle = ...
                load_system(targetModelFile);

            loadedName = ...
                get_param(targetHandle, 'Name');

            agentBlock = ...
                [loadedName, '/RL agent'];

            actionOutBlock = ...
                [loadedName, '/ActionOut'];

            rebuild = ...
                getSimulinkBlockHandle(agentBlock) == -1 || ...
                getSimulinkBlockHandle(actionOutBlock) == -1 || ...
                ~strcmp( ...
                    get_param(agentBlock, 'System'), ...
                    agentClass ...
                );

            close_system(loadedName, 0);

        catch
            rebuild = true;
            bdclose('all');
        end
    end

    if ~rebuild
        return;
    end

    if isfile(targetModelFile)

        timestamp = char(datetime( ...
            'now', ...
            'Format', 'yyyyMMdd_HHmmss_SSS' ...
        ));

        backupFile = fullfile( ...
            generatedDirectory, ...
            [ ...
                targetModelName, ...
                '_backup_', ...
                timestamp, ...
                sourceExtension ...
            ] ...
        );

        copyfile(targetModelFile, backupFile);
        delete(targetModelFile);
    end

    bdclose('all');

    sourceHandle = ...
        load_system(sourceModelFile);

    sourceModelName = ...
        get_param(sourceHandle, 'Name');

    save_system( ...
        sourceModelName, ...
        targetModelFile ...
    );

    close_system(sourceModelName, 0);
    bdclose('all');

    targetHandle = ...
        load_system(targetModelFile);

    loadedTargetName = ...
        get_param(targetHandle, 'Name');

    assert(strcmp(loadedTargetName, targetModelName), ...
        [ ...
            'Generated model name mismatch.\n' ...
            'Expected: %s\n' ...
            'Actual:   %s' ...
        ], ...
        targetModelName, ...
        loadedTargetName);

    agentBlock = ...
        [targetModelName, '/RL agent'];

    assert(getSimulinkBlockHandle(agentBlock) ~= -1, ...
        'RL agent block was not found in %s.', ...
        targetModelName);

    set_param( ...
        agentBlock, ...
        'System', ...
        agentClass ...
    );

    actionOutBlock = ...
        [targetModelName, '/ActionOut'];

    if getSimulinkBlockHandle(actionOutBlock) ~= -1
        delete_block(actionOutBlock);
    end

    add_block( ...
        'simulink/Sinks/Out1', ...
        actionOutBlock, ...
        'Port', '3', ...
        'Position', [450 40 480 60] ...
    );

    add_line( ...
        targetModelName, ...
        'RL agent/1', ...
        'ActionOut/1', ...
        'autorouting', 'on' ...
    );

    set_param( ...
        targetModelName, ...
        'SaveTime', 'on', ...
        'TimeSaveName', 'tout', ...
        'SaveOutput', 'on', ...
        'OutputSaveName', 'yout', ...
        'SaveFormat', 'Dataset' ...
    );

    save_system(targetModelName);
    close_system(targetModelName, 0);
end


function ensureDenseAfcStateOutput_( ...
        targetModelFile, ...
        targetModelName, ...
        stateSampleTime)

    % The legacy AFC RL wrapper feeds its normalized state only to a
    % 5-second discrete agent. Simulink therefore logs Out2 at 5-second
    % instants and misses the AFC transients that the official requirement
    % evaluates on a 0.01-second trace. Keep the action/agent rate intact,
    % but create a separate dense state branch for the monitor and Out2.

    denseMuxName = ...
        'ARCH2025 Dense State Mux';
    denseNormalizerName = ...
        'ARCH2025 Dense State Normalizer';

    bdclose('all');
    targetHandle = load_system(targetModelFile);
    loadedTargetName = get_param(targetHandle, 'Name');

    assert(strcmp(loadedTargetName, targetModelName), ...
        'Unexpected AFC generated model name: %s', loadedTargetName);

    denseMuxBlock = ...
        [targetModelName, '/', denseMuxName];
    denseNormalizerBlock = ...
        [targetModelName, '/', denseNormalizerName];
    sourceMuxBlock = ...
        [targetModelName, '/Mux'];
    sourceNormalizerBlock = ...
        [targetModelName, '/MATLAB Function2'];

    if getSimulinkBlockHandle(denseMuxBlock) ~= -1 && ...
            getSimulinkBlockHandle(denseNormalizerBlock) ~= -1

        legacyBlocksRemoved = false;

        if getSimulinkBlockHandle(sourceNormalizerBlock) ~= -1
            delete_block(sourceNormalizerBlock);
            legacyBlocksRemoved = true;
        end

        if getSimulinkBlockHandle(sourceMuxBlock) ~= -1
            delete_block(sourceMuxBlock);
            legacyBlocksRemoved = true;
        end

        unconnectedLinesRemoved = ...
            deleteUnconnectedLines_(targetModelName);

        if legacyBlocksRemoved || unconnectedLinesRemoved
            save_system(targetModelName);
        end

        close_system(targetModelName, 0);
        return;
    end

    assert(getSimulinkBlockHandle(sourceMuxBlock) ~= -1, ...
        'AFC source state Mux was not found in %s.', targetModelName);
    assert(getSimulinkBlockHandle(sourceNormalizerBlock) ~= -1, ...
        'AFC source state normalizer was not found in %s.', ...
        targetModelName);

    sourceMuxPorts = get_param(sourceMuxBlock, 'PortHandles');
    numberOfStates = numel(sourceMuxPorts.Inport);

    assert(numberOfStates == 4, ...
        'AFC state Mux must have four scalar inputs. Actual: %d', ...
        numberOfStates);

    sourceSignalPorts = zeros(numberOfStates, 1);

    for stateIndex = 1:numberOfStates
        inputLine = get_param( ...
            sourceMuxPorts.Inport(stateIndex), 'Line');

        assert(inputLine ~= -1, ...
            'AFC state Mux input %d is not connected.', stateIndex);

        sourceSignalPorts(stateIndex) = ...
            get_param(inputLine, 'SrcPortHandle');
    end

    add_block( ...
        'simulink/Signal Routing/Mux', ...
        denseMuxBlock, ...
        'Inputs', num2str(numberOfStates), ...
        'Position', [510 340 515 480] ...
    );

    denseMuxPorts = get_param(denseMuxBlock, 'PortHandles');

    for stateIndex = 1:numberOfStates

        denseHoldName = sprintf( ...
            'ARCH2025 Dense State Hold %d', stateIndex);
        denseHoldBlock = ...
            [targetModelName, '/', denseHoldName];

        verticalPosition = 330 + 40 * stateIndex;

        add_block( ...
            'simulink/Discrete/Zero-Order Hold', ...
            denseHoldBlock, ...
            'SampleTime', num2str(stateSampleTime, 17), ...
            'Position', [400 verticalPosition 440 verticalPosition + 20] ...
        );

