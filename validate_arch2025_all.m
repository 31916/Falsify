clearvars;
clear classes;
clc;

% =========================================================
% ARCH-COMP 2025 unified Falsify validation batch
%
% One execution covers:
%   Models      : SB, AT, AFC, CC, NN, F16, SC
%   Algorithms  : RAND, A3C, ACER, DDQN
%   Requirements:
%       SB  : SB1-SB5
%       AT  : AT1, AT2, AT51-AT54, AT6a-AT6c, AT6abc
%       AFC : AFC27, AFC29, AFC33
%       CC  : CC1-CC5, CCx
%       NN  : NN, NNb (beta = 0.04), NNx
%       F16: F16a
%       SC  : SCa
%   Instances:
%       AT, CC, NN : Instance 1 and Instance 2
%       AFC, SB    : Instance 2
%
% Total:
%   49 benchmark conditions x 4 algorithms = 196 cases
%
% Every case:
%   1. Runs Falsify.
%   2. Extracts the actual generated input.
%   3. Checks the ARCH-COMP input constraints.
%   4. Replays the input on the local official ARCH-COMP model.
%   5. Computes official robustness on the official trace.
%   6. Records classification agreement.
%   7. Continues after errors.
%
% Default execution budget is one Falsify episode per case.
% This is a validation batch, not the final repeated experiment.
% =========================================================

repoDirectory = fileparts(mfilename('fullpath'));
workspaceDirectory = fileparts(repoDirectory);

% Optional wildcard used for focused local verification. Examples:
%   cc_cc1_i2_rand
%   cc_*_i2_*
caseFilter = ...
    lower(strtrim(string( ...
        getenv('FALSIFY_ARCH2025_CASE_FILTER') ...
    )));

officialRootDirectory = strtrim( ...
    getenv('FALSIFY_ARCH2025_OFFICIAL_ROOT'));
if isempty(officialRootDirectory)
    officialRootDirectory = fullfile( ...
        workspaceDirectory, 'ARCH-COMP', 'ARCH-COMP-full', ...
        'models', 'FALS');
end

falBenchRootDirectory = strtrim( ...
    getenv('FALSIFY_ARCH2025_FALBENCH_ROOT'));
if isempty(falBenchRootDirectory)
    falBenchRootDirectory = fullfile( ...
        workspaceDirectory, 'ARCH-COMP', 'FalBenchGen');
end

pythonExecutable = strtrim( ...
    getenv('FALSIFY_ARCH2025_PYTHON'));
if isempty(pythonExecutable)
    pythonExecutable = fullfile( ...
        repoDirectory, '.venv-falsify', 'bin', 'python');
end

baseResultsDirectory = ...
    fullfile( ...
        repoDirectory, ...
        'results', ...
        'arch2025' ...
    );

resultsDirectory = ...
    fullfile(baseResultsDirectory, 'all');

explicitResultsDirectory = strtrim(string( ...
    getenv('FALSIFY_ARCH2025_OUTPUT_DIR')));

if strlength(explicitResultsDirectory) > 0

    if startsWith(explicitResultsDirectory, filesep) || ...
            ~isempty(regexp( ...
                explicitResultsDirectory, '^[A-Za-z]:[\\/]', 'once'))
        resultsDirectory = char(explicitResultsDirectory);
    else
        resultsDirectory = fullfile( ...
            repoDirectory, char(explicitResultsDirectory));
    end

elseif strlength(caseFilter) > 0

    caseFilterLabel = ...
        regexprep(caseFilter, '[^a-z0-9_-]+', '_');

    resultsDirectory = ...
        fullfile( ...
            baseResultsDirectory, ...
            'selected', ...
            char(caseFilterLabel) ...
        );
end

summaryFile = ...
    fullfile( ...
        resultsDirectory, ...
        'arch2025_all_summary.csv' ...
    );

reportFile = ...
    fullfile( ...
        resultsDirectory, ...
        'arch2025_all_report.txt' ...
    );

caseTraceDirectory = ...
    fullfile( ...
        resultsDirectory, ...
        'traces' ...
    );

generatedDirectory = ...
    fullfile( ...
        repoDirectory, ...
        'arch2025_generated' ...
    );

% ---------------------------------------------------------
% Batch options
% ---------------------------------------------------------

algorithms = [
    "RAND"
    "A3C"
    "ACER"
    "DDQN"
];

maxEpisodes = 1;
baseSeed = 20250730;
seedOverride = NaN;
traceStep = 0.01;

maxEpisodesSetting = strtrim(string( ...
    getenv('FALSIFY_ARCH2025_MAX_EPISODES') ...
));

if strlength(maxEpisodesSetting) > 0
    configuredMaxEpisodes = str2double(maxEpisodesSetting);
    assert(isfinite(configuredMaxEpisodes) && ...
        configuredMaxEpisodes >= 1 && ...
        configuredMaxEpisodes == floor(configuredMaxEpisodes), ...
        'FALSIFY_ARCH2025_MAX_EPISODES must be a positive integer.');
    maxEpisodes = configuredMaxEpisodes;
end

seedOverrideSetting = strtrim(string( ...
    getenv('FALSIFY_ARCH2025_SEED_OVERRIDE') ...
));

if strlength(seedOverrideSetting) > 0
    configuredSeed = str2double(seedOverrideSetting);
    assert(isfinite(configuredSeed) && ...
        configuredSeed >= 0 && ...
        configuredSeed <= double(intmax('int32')) && ...
        configuredSeed == floor(configuredSeed), ...
        ['FALSIFY_ARCH2025_SEED_OVERRIDE must be an integer ' ...
         'between 0 and intmax(''int32'').']);
    seedOverride = configuredSeed;
end

inputTolerance = 1.0e-9;
changeTimeTolerance = 1.0e-6;
classificationTolerance = 1.0e-9;
trajectoryTolerance = 1.0e-6;

% By default, skip cases already recorded as OverallPass=true. Set the
% environment variable to 0/false/no for a clean focused re-run.
resumeSetting = lower(strtrim(string( ...
    getenv('FALSIFY_ARCH2025_RESUME_PASSED') ...
)));
resumePassedCases = ~ismember( ...
    resumeSetting, ...
    ["0", "false", "no"] ...
);

% =========================================================
% Preflight
% =========================================================

assert(isfolder(repoDirectory), ...
    'Falsify directory was not found:\n%s', ...
    repoDirectory);

assert(isfolder(officialRootDirectory), ...
    'Official ARCH-COMP model directory was not found:\n%s', ...
    officialRootDirectory);

assert(isfolder(falBenchRootDirectory), ...
    'FalBenchGen directory was not found:\n%s', ...
    falBenchRootDirectory);

assert(isfile(pythonExecutable), ...
    'Falsify Python executable was not found:\n%s', ...
    pythonExecutable);

ensureDirectory_(resultsDirectory);
ensureDirectory_(caseTraceDirectory);
ensureDirectory_(generatedDirectory);

cd(repoDirectory);
bdclose('all');

restorePaths_(repoDirectory, generatedDirectory);

atDataFile = locateArch2025AtData_();
if isfile(atDataFile)
    addpath(fileparts(atDataFile), '-begin');
end

preparePython_(pythonExecutable, repoDirectory);

% =========================================================
% Build/reuse all generated wrappers before the batch
% =========================================================

wrapperCatalog = prepareAllWrappers_( ...
    repoDirectory, ...
    generatedDirectory, ...
    officialRootDirectory, ...
    falBenchRootDirectory ...
);

% =========================================================
% Build the full 196-case catalog
% =========================================================

settings = struct();

settings.RepoDirectory = repoDirectory;
settings.OfficialRootDirectory = officialRootDirectory;
settings.FalBenchRootDirectory = falBenchRootDirectory;
settings.GeneratedDirectory = generatedDirectory;
settings.ResultsDirectory = resultsDirectory;
settings.CaseTraceDirectory = caseTraceDirectory;
settings.AtDataFile = atDataFile;

settings.MaxEpisodes = maxEpisodes;
settings.BaseSeed = baseSeed;
settings.TraceStep = traceStep;

settings.InputTolerance = inputTolerance;
settings.ChangeTimeTolerance = changeTimeTolerance;
settings.ClassificationTolerance = classificationTolerance;
settings.TrajectoryTolerance = trajectoryTolerance;

settings.Wrappers = wrapperCatalog;

allCases = buildAllCases_(algorithms, settings);

assert(numel(allCases) == 196, ...
    'The unified catalog must contain 196 cases. Actual: %d', ...
    numel(allCases));

catalogCaseIds = vertcat(allCases.CaseID);
cases = allCases;

if strlength(caseFilter) > 0

    caseFilterExpression = [ ...
        '^', ...
        regexptranslate('wildcard', char(caseFilter)), ...
        '$' ...
    ];

    selectedRows = arrayfun( ...
        @(currentCase) ~isempty(regexp( ...
            char(currentCase.CaseID), ...
            caseFilterExpression, ...
            'once' ...
        )), ...
        cases ...
    );

    assert(any(selectedRows), ...
        'Case filter matched no cases: %s', ...
        caseFilter);

    cases = cases(selectedRows);
end

% =========================================================
% Resume information
% =========================================================

previousResults = table();

if resumePassedCases && isfile(summaryFile)

    try
        previousResults = readtable( ...
            summaryFile, ...
            'TextType', 'string' ...
        );
    catch
        previousResults = table();
    end
end

% =========================================================
% Start report
% =========================================================

if isfile(reportFile)
    delete(reportFile);
end

diary(reportFile);
cleanupObject = onCleanup(@() cleanupBatch_());

fprintf('============================================================\n');
fprintf('ARCH-COMP 2025 unified Falsify validation batch\n');
fprintf('============================================================\n\n');

fprintf('Cases:              %d\n', numel(cases));
fprintf('Algorithms:         RAND, A3C, ACER, DDQN\n');
fprintf('Episodes per case:  %d\n', maxEpisodes);
fprintf('Official grid:      %.2f seconds\n', traceStep);

if isfinite(seedOverride)
    fprintf('Seed override:      %d\n', seedOverride);
else
    fprintf('Base seed:          %d (plus catalog index)\n', baseSeed);
end

if strlength(caseFilter) > 0
    fprintf('Case filter:        %s\n', caseFilter);
else
    fprintf('Case filter:        (none)\n');
end

fprintf('Results directory:\n%s\n\n', resultsDirectory);

if isfile(atDataFile)
    fprintf('AT support data:\n%s\n\n', atDataFile);
else
    fprintf([ ...
        'AT support data:   not found ' ...
        '(non-AT cases may still run)\n\n' ...
    ]);
end

fprintf('Generated/reused wrappers:\n');
disp(struct2table(wrapperCatalog));

% =========================================================
% Execute every case
% =========================================================

resultTemplate = emptyResult_();
results = repmat(resultTemplate, numel(cases), 1);

for caseIndex = 1:numel(cases)

    currentCase = cases(caseIndex);

    fprintf('\n');
    fprintf('############################################################\n');
    fprintf('Case %d / %d\n', caseIndex, numel(cases));
    fprintf('ID:          %s\n', currentCase.CaseID);
    fprintf('Model:       %s\n', currentCase.Model);
    fprintf('Requirement: %s\n', currentCase.Requirement);
    fprintf('Instance:    %d\n', currentCase.Instance);
    fprintf('Algorithm:   %s\n', currentCase.Algorithm);
    fprintf('############################################################\n\n');

    catalogIndex = find( ...
        catalogCaseIds == currentCase.CaseID, ...
        1, ...
        'first' ...
    );

    if isfinite(seedOverride)
        seed = seedOverride;
    else
        seed = baseSeed + catalogIndex - 1;
    end

    previousRow = findPreviousPassedRow_( ...
        previousResults, ...
        currentCase.CaseID ...
    );

    if ~isempty(previousRow)

        results(caseIndex) = ...
            tableRowToResult_(previousRow);

        fprintf('Skipped: an OverallPass=true result already exists.\n');

        continue;
    end

    try

        restorePaths_(repoDirectory, generatedDirectory);
        bdclose('all');

        setAllSeeds_(seed);

        results(caseIndex) = ...
            runOneCase_( ...
                currentCase, ...
                seed, ...
                settings ...
            );

    catch caseError

        failedResult = emptyResult_();

        failedResult.CaseID = currentCase.CaseID;
        failedResult.Model = currentCase.Model;
        failedResult.Requirement = currentCase.Requirement;
        failedResult.Instance = currentCase.Instance;
        failedResult.Algorithm = currentCase.Algorithm;
        failedResult.Seed = seed;
        failedResult.Status = "ERROR";
        failedResult.ErrorIdentifier = ...
            string(caseError.identifier);
        failedResult.ErrorMessage = ...
            compactErrorMessage_(caseError);

        results(caseIndex) = failedResult;

        fprintf('Case result: ERROR\n');
        fprintf('Identifier: %s\n', failedResult.ErrorIdentifier);
        fprintf('Message:\n%s\n\n', failedResult.ErrorMessage);
    end

    % Save after every case so that an interrupted batch can resume.
    partialTable = struct2table(results(1:caseIndex));
    writetable(partialTable, summaryFile);

    try
        bdclose('all');
    catch
    end

    cd(repoDirectory);
end

% =========================================================
% Final summary
% =========================================================

summaryTable = struct2table(results);
writetable(summaryTable, summaryFile);

fprintf('\n');
fprintf('============================================================\n');
fprintf('FINAL UNIFIED SUMMARY\n');
fprintf('============================================================\n\n');

displayColumns = { ...
    'Model', ...
    'Requirement', ...
    'Instance', ...
    'Algorithm', ...
    'Status', ...
    'InputPass', ...
    'OfficialReplayPass', ...
    'ClassificationAgreementPass', ...
    'TrajectoryEquivalencePass', ...
    'OverallPass' ...
};

disp(summaryTable(:, displayColumns));

validatedCount = sum(summaryTable.OverallPass);
errorCount = sum(summaryTable.Status == "ERROR");

fprintf('Validated cases: %d / %d\n', ...
    validatedCount, ...
    height(summaryTable));

fprintf('Errored cases:   %d / %d\n\n', ...
    errorCount, ...
    height(summaryTable));

modelNames = [
    "SB"
    "AT"
    "AFC"
    "CC"
    "NN"
    "F16"
    "SC"
];

for modelIndex = 1:numel(modelNames)

    modelName = modelNames(modelIndex);
    modelRows = summaryTable.Model == modelName;

    fprintf('%s: %d / %d validated\n', ...
        modelName, ...
        sum(summaryTable.OverallPass(modelRows)), ...
        sum(modelRows));
end

fprintf('\nSummary CSV:\n%s\n\n', summaryFile);
fprintf('Report:\n%s\n\n', reportFile);
fprintf('Trace directory:\n%s\n', caseTraceDirectory);

diary off;

fprintf('\nUnified validation batch completed.\n');


% =========================================================
% Case execution
% =========================================================

function result = runOneCase_( ...
        currentCase, ...
        seed, ...
        settings)

    result = emptyResult_();

    result.CaseID = currentCase.CaseID;
    result.Model = currentCase.Model;
    result.Requirement = currentCase.Requirement;
    result.Instance = currentCase.Instance;
    result.Algorithm = currentCase.Algorithm;
    result.Seed = seed;
    result.Status = "RUNNING";

    prepareArch2025AtCase_(currentCase, settings);

    config = makeFalsifyConfig_(currentCase, settings);

    assignInitialValues_(config.init_opts);

    fprintf('Falsify model: %s\n', config.mdl);
    fprintf('Formula:       %s\n', config.targetFormula);
    fprintf('Stop time:     %.12g\n', config.stopTime);
    fprintf('Sample time:   %.12g\n\n', config.sampleTime);

    [numberOfEpisodes, ...
        elapsedTime, ...
        falsifyRobustness, ...
        ~, ...
        bestYout ...
    ] = falsify(config);

    result.FalsifyRunPass = true;
    result.Episodes = numberOfEpisodes;
    result.ElapsedSeconds = elapsedTime;
    result.FalsifyRobustness = falsifyRobustness;
    result.FalsifyClassification = robustnessClassText_( ...
        falsifyRobustness, settings.ClassificationTolerance);

    [stateTime, ...
        normalizedState, ...
        stateElementName ...
    ] = readDatasetElement_(bestYout, 2);

    [actionTime, ...
        actionData, ...
        actionElementName ...
    ] = readDatasetElement_(bestYout, 3);

    fprintf('State element:  %s\n', stateElementName);
    fprintf('Action element: %s\n', actionElementName);

    assert(size(normalizedState, 2) == ...
        size(config.output_range, 1), ...
        [ ...
            'State dimension mismatch.\n' ...
            'Expected: %d\n' ...
            'Actual:   %d' ...
        ], ...
        size(config.output_range, 1), ...
        size(normalizedState, 2));

    assert(size(actionData, 2) == ...
        size(config.input_range, 1), ...
        [ ...
            'Action dimension mismatch.\n' ...
            'Expected: %d\n' ...
            'Actual:   %d' ...
        ], ...
        size(config.input_range, 1), ...
        size(actionData, 2));

    [uniqueStateTime, ...
        uniqueNormalizedState ...
    ] = uniqueTimeSeriesLast_( ...
        stateTime, ...
        normalizedState ...
    );

    [uniqueActionTime, ...
        uniqueActionData ...
    ] = uniqueTimeSeriesLast_( ...
        actionTime, ...
        actionData ...
    );

    rawState = denormalizeState_( ...
        uniqueNormalizedState, ...
        config.output_range ...
    );

    stateTraceFile = fullfile( ...
        settings.CaseTraceDirectory, ...
        [char(currentCase.CaseID), '_state.csv'] ...
    );

    stateTraceVariableNames = [ ...
        "Time", ...
        "NormalizedState" + (1:size(uniqueNormalizedState, 2)), ...
        "RawState" + (1:size(rawState, 2)) ...
    ];

    stateTraceTable = array2table( ...
        [ ...
            uniqueStateTime, ...
            uniqueNormalizedState, ...
            rawState ...
        ], ...
        'VariableNames', cellstr(stateTraceVariableNames) ...
    );

    writetable(stateTraceTable, stateTraceFile);
    result.StateTraceFile = string(stateTraceFile);

    [inputPass, ...
        inputRangePass, ...
        inputStructurePass, ...
        inputMessage, ...
        officialInputTime, ...
        officialInputData ...
    ] = validateAndCreateOfficialInput_( ...
        currentCase, ...
        uniqueActionTime, ...
        uniqueActionData, ...
        config.input_range, ...
        settings ...
    );

    result.InputRangePass = inputRangePass;
    result.InputStructurePass = inputStructurePass;
    result.InputPass = inputPass;
    result.InputMessage = inputMessage;

    traceFile = fullfile( ...
        settings.CaseTraceDirectory, ...
        [char(currentCase.CaseID), '_input.csv'] ...
    );

    inputTable = array2table( ...
        [officialInputTime, officialInputData] ...
    );

    inputTable.Properties.VariableNames = ...
        inputVariableNames_(currentCase.Model);

    writetable(inputTable, traceFile);

    result.InputTraceFile = string(traceFile);

    fprintf('Input range:     %s\n', passText_(inputRangePass));
    fprintf('Input structure: %s\n', passText_(inputStructurePass));
    fprintf('Input result:    %s\n', passText_(inputPass));
    fprintf('Input details:   %s\n\n', inputMessage);

    if ~inputPass

        result.Status = "INPUT_FAILED";
        result.OverallPass = false;

        fprintf('Official replay skipped because input validation failed.\n');

        return;
    end

    [officialTime, ...
        officialRawOutput ...
    ] = runOfficialModel_( ...
        currentCase, ...
        officialInputTime, ...
        officialInputData, ...
        settings ...
    );

    result.OfficialReplayPass = true;

    officialState = canonicalOfficialState_( ...
        currentCase, ...
        officialTime, ...
        officialRawOutput, ...
        officialInputTime, ...
        officialInputData ...
    );

    assert(size(officialState, 2) == ...
        size(config.output_range, 1), ...
        [ ...
            'Official canonical state dimension mismatch.\n' ...
            'Expected: %d\n' ...
            'Actual:   %d' ...
        ], ...
        size(config.output_range, 1), ...
        size(officialState, 2));

    officialRobustness = dp_taliro( ...
        char(currentCase.Formula), ...
        currentCase.Preds, ...
        officialState, ...
        officialTime, ...
        [], ...
        [], ...
        [] ...
    );

    result.OfficialRobustness = officialRobustness;
    result.OfficialClassification = robustnessClassText_( ...
        officialRobustness, settings.ClassificationTolerance);

    classificationAgreement = sameClassification_( ...
        falsifyRobustness, ...
        officialRobustness, ...
        settings.ClassificationTolerance ...
    );

    result.ClassificationAgreementPass = ...
        classificationAgreement;

    [maximumTrajectoryError, ...
        trajectoryPass ...
    ] = trajectoryDiagnostic_( ...
        uniqueStateTime, ...
        rawState, ...
        officialTime, ...
        officialState, ...
        currentCase.StopTime, ...
        settings ...
    );

    result.MaximumTrajectoryError = ...
        maximumTrajectoryError;

    result.TrajectoryEquivalencePass = ...
        trajectoryPass;

    result.OverallPass = ...
        result.FalsifyRunPass && ...
        result.InputPass && ...
        result.OfficialReplayPass && ...
        result.ClassificationAgreementPass;

    if result.OverallPass
        result.Status = "VALIDATED";
    else
        result.Status = "FAILED";
    end

    fprintf('Falsify robustness:  %.12g\n', ...
        falsifyRobustness);

    fprintf('Official robustness: %.12g\n', ...
        officialRobustness);

    fprintf('Classification:      %s\n', ...
        passText_(classificationAgreement));

    fprintf('Maximum trace error: %.12e\n', ...
        maximumTrajectoryError);

    fprintf('Trajectory diagnostic: %s\n', ...
        passText_(trajectoryPass));

    fprintf('Overall validation:    %s\n\n', ...
        passText_(result.OverallPass));
end


% =========================================================
% Full case catalog
% =========================================================

function cases = buildAllCases_(algorithms, settings)

    cases = repmat(emptyCase_(), 0, 1);

    modelRequirements = {
        "SB",  [
            "SB1"
            "SB2"
            "SB3"
            "SB4"
            "SB5"
        ], 2

        "AT",  [
            "AT1"
            "AT2"
            "AT51"
            "AT52"
            "AT53"
            "AT54"
            "AT6a"
            "AT6b"
            "AT6c"
            "AT6abc"
        ], [1 2]

        "AFC", [
            "AFC27"
            "AFC29"
            "AFC33"
        ], 2

        "CC", [
            "CC1"
            "CC2"
            "CC3"
            "CC4"
            "CC5"
            "CCx"
        ], [1 2]

        "NN", [
            "NN"
            "NNb"
            "NNx"
        ], [1 2]

        "F16", "F16a", 1

        "SC", "SCa", [1 2]
    };

    for modelRow = 1:size(modelRequirements, 1)

        modelName = modelRequirements{modelRow, 1};
        requirements = modelRequirements{modelRow, 2};
        instances = modelRequirements{modelRow, 3};

        for requirementIndex = 1:numel(requirements)

            requirementName = ...
                requirements(requirementIndex);

            requirementSpec = ...
                makeRequirementSpec_( ...
                    modelName, ...
                    requirementName ...
                );

            for instanceIndex = 1:numel(instances)

                instanceNumber = ...
                    instances(instanceIndex);

                instanceSpec = ...
                    makeInstanceSpec_( ...
                        modelName, ...
                        requirementName, ...
                        instanceNumber, ...
                        settings ...
                    );

                for algorithmIndex = 1:numel(algorithms)

                    algorithm = ...
                        algorithms(algorithmIndex);

                    currentCase = emptyCase_();

                    currentCase.Model = modelName;
                    currentCase.Requirement = requirementName;
                    currentCase.Instance = instanceNumber;
                    currentCase.Algorithm = algorithm;

                    currentCase.CaseID = ...
                        lower( ...
                            modelName + "_" + ...
                            requirementName + "_i" + ...
                            string(instanceNumber) + "_" + ...
                            algorithm ...
                        );

                    currentCase.Formula = ...
                        requirementSpec.Formula;

                    currentCase.MonitoringFormula = ...
                        requirementSpec.MonitoringFormula;

                    currentCase.Preds = ...
                        requirementSpec.Preds;

                    currentCase.ModelName = ...
                        instanceSpec.ModelName;

                    currentCase.AgentName = ...
                        '/RL agent';

                    currentCase.InputRange = ...
                        instanceSpec.InputRange;

                    currentCase.OutputRange = ...
                        instanceSpec.OutputRange;

                    currentCase.Outputs = ...
                        instanceSpec.Outputs;

                    currentCase.InitOptions = ...
                        instanceSpec.InitOptions;

                    currentCase.Interpolation = ...
                        instanceSpec.Interpolation;

                    currentCase.SampleTime = ...
                        instanceSpec.SampleTime;

                    currentCase.StopTime = ...
                        instanceSpec.StopTime;

                    currentCase.OfficialDirectory = ...
                        instanceSpec.OfficialDirectory;

                    currentCase.OfficialRunFunction = ...
                        instanceSpec.OfficialRunFunction;

                    currentCase.OfficialAsset = ...
                        instanceSpec.OfficialAsset;

                    cases(end + 1, 1) = currentCase; %#ok<AGROW>
                end
            end
        end
    end
end


function spec = makeInstanceSpec_( ...
        modelName, ...
        requirementName, ...
        instanceNumber, ...
        settings)

    spec = struct();

    switch modelName

        case "SB"

            wrapperField = ...
                ['SB_', char(upper(requirementName))];

            assert(isfield(settings.Wrappers, wrapperField), ...
                'Missing SB wrapper: %s', wrapperField);

            spec.ModelName = settings.Wrappers.(wrapperField);
            spec.Interpolation = "pconst";
            spec.SampleTime = 6;
            spec.StopTime = 24;
            spec.InputRange = [0.0 1.0];
            spec.Outputs = 1;

            if ismember(requirementName, ["SB4", "SB5"])
                spec.OutputRange = repmat([-100.0 100.0], 2, 1);
                spec.Outputs = [1 2];
            elseif requirementName == "SB2"
                spec.OutputRange = [0.0 100.0];
            else
                spec.OutputRange = [-50.0 50.0];
            end

            spec.InitOptions = {};
            spec.OfficialDirectory = settings.FalBenchRootDirectory;
            spec.OfficialRunFunction = "predict";

            networkRelativeFiles = struct( ...
                'SB1', fullfile( ...
                    'Model', 'Model_matlab_delta=2', ...
                    's1a2_k1_1_4_9_10_0.01_LSTM', ...
                    's1a2_k1_1.mat'), ...
                'SB2', fullfile( ...
                    'Model', 'Model_matlab_delta=2', ...
                    's3a2_k1_1_4_9_10_0.01_LSTM', ...
                    's3a2_k1_1.mat'), ...
                'SB3', fullfile( ...
                    'Model', 'Model_matlab_delta=2', ...
