function paths = fim_paths()
%FIM_PATHS Resolve paths from the repository, not the current directory.
root=fileparts(fileparts(mfilename('fullpath')));
repo=fileparts(fileparts(root));
deps=fullfile(repo,'.deps','fim');
paths=struct('Experiment',root,'Repo',repo,'Dependencies',deps, ...
    'FIMOriginal',fullfile(deps,'fimtool'), ...
    'FIMPatched',fullfile(deps,'fimtool-r2026a'), ...
    'ATModel',fullfile(deps,'arch','models','FALS','transmission','Autotrans_shift.mdl'), ...
    'ModelData',fullfile(deps,'model-data'));
assert(isfile(fullfile(deps,'installed.json')), ...
    'FIM dependencies missing. Run experiments/fim/dependencies/prepare.py; see experiments/fim/README.md.');
assert(isfile(paths.ATModel) && isfile(fullfile(paths.ModelData,'sldemo_autotrans_data.mat')), ...
    'FIM model dependencies are incomplete. See experiments/fim/README.md.');
end
